import { Command, Config, Job, commands, reusable } from '../../circleci-config';
import { DockerLoginCommand, DockerLogoutCommand, InstallYarnCommand, NotifyOnFailureCommand } from '../../commands';
import { computeImagesTag } from '../../utils';
import { CircleCIEnvironment } from '../../pipelines';
import { UbuntuExecutor } from '../../executors';

export class E2EPlaywrightJob {
  private static jobName = `job-e2e-playwright`;
  public static create(dynamicConfig: Config, environment: CircleCIEnvironment): Job {
    const installYarnCmd = InstallYarnCommand.get();
    const dockerLoginCmd = DockerLoginCommand.get(dynamicConfig, environment, false);
    const dockerLogoutCmd = DockerLogoutCommand.get(environment, false);
    const notifyOnFailureCmd = NotifyOnFailureCommand.get(dynamicConfig, environment);
    dynamicConfig.addReusableCommand(installYarnCmd);
    dynamicConfig.addReusableCommand(dockerLoginCmd);
    dynamicConfig.addReusableCommand(dockerLogoutCmd);
    dynamicConfig.addReusableCommand(notifyOnFailureCmd);

    const dockerImageTag = computeImagesTag(environment.branch, environment.sha1);

    const steps: Command[] = [
      new commands.Checkout(),
      // Brings in the SDK clients generated by "Generate e2e tests SDK". They are gitignored, so a
      // checkout alone leaves the suite unable to compile.
      new commands.workspace.Attach({ at: '.' }),
      new reusable.ReusedCommand(dockerLoginCmd),
      new reusable.ReusedCommand(installYarnCmd),
      new commands.Run({
        name: `Running Playwright UI tests`,
        command: `cd gravitee-apim-distribution/gravitee-apim-distribution-e2e
APIM_REGISTRY=graviteeio.azurecr.io APIM_TAG=${dockerImageTag} yarn test:pw`,
      }),
      new reusable.ReusedCommand(dockerLogoutCmd),
      new reusable.ReusedCommand(notifyOnFailureCmd),
      new commands.StoreTestResults({
        path: './gravitee-apim-distribution/gravitee-apim-distribution-e2e/.tmp/playwright/junit',
      }),
      new commands.StoreArtifacts({
        path: './gravitee-apim-distribution/gravitee-apim-distribution-e2e/.tmp/playwright/html-report',
      }),
      new commands.StoreArtifacts({
        path: './gravitee-apim-distribution/gravitee-apim-distribution-e2e/.tmp/playwright/test-results',
      }),
      new commands.StoreArtifacts({
        path: './gravitee-apim-distribution/gravitee-apim-distribution-e2e/.logs',
      }),
    ];
    return new Job(E2EPlaywrightJob.jobName, UbuntuExecutor.create('large'), steps);
  }
}
