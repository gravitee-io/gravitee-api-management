package io.gravitee.rest.api.portal.rest.resource;

import io.gravitee.common.http.MediaType;
import io.gravitee.rest.api.portal.rest.model.SubscriptionInput;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;
import jakarta.ws.rs.Consumes;
import jakarta.ws.rs.POST;
import jakarta.ws.rs.Produces;
import jakarta.ws.rs.container.ResourceContext;
import jakarta.ws.rs.core.Context;
import jakarta.ws.rs.core.Response;

/**
 * Subscribing from one portal: only to the APIs and API products the portal lists for the viewer. Reading and managing subscriptions
 * stays on the unscoped path, since a user's subscriptions are shared by every portal.
 */
public class PortalSubscriptionsResource extends AbstractResource {

    @Context
    private ResourceContext resourceContext;

    @POST
    @Consumes(MediaType.APPLICATION_JSON)
    @Produces(MediaType.APPLICATION_JSON)
    public Response createSubscription(@Valid @NotNull(message = "Input must not be null.") SubscriptionInput subscriptionInput) {
        return resourceContext
            .getResource(SubscriptionsResource.class)
            .createSubscription(subscriptionInput, PortalScope.fromPath(uriInfo));
    }
}
