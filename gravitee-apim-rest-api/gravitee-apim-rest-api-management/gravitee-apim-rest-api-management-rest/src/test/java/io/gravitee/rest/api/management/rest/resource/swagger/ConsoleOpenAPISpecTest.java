package io.gravitee.rest.api.management.rest.resource.swagger;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

class ConsoleOpenAPISpecTest {

    private static JsonNode spec;

    @BeforeAll
    static void loadGeneratedSpec() throws IOException {
        try (InputStream in = ConsoleOpenAPISpecTest.class.getClassLoader().getResourceAsStream("console-openapi.json")) {
            assertThat(in).as("console-openapi.json must be generated by swagger-maven-plugin-jakarta before tests").isNotNull();
            spec = new ObjectMapper().readTree(in);
        }
    }

    @Test
    void should_declare_client_certificate_as_create_certificate_201_schema() {
        List<String> refs = new ArrayList<>();
        spec
            .path("paths")
            .fields()
            .forEachRemaining(path -> {
                if (path.getKey().endsWith("/certificates") && !path.getKey().contains("_validate")) {
                    JsonNode ref = path
                        .getValue()
                        .path("post")
                        .path("responses")
                        .path("201")
                        .path("content")
                        .path("application/json")
                        .path("schema")
                        .path("$ref");
                    if (!ref.isMissingNode()) {
                        refs.add(ref.asText());
                    }
                }
            });

        assertThat(refs)
            .isNotEmpty()
            .allMatch(ref -> ref.endsWith("/ClientCertificate"));
    }

    @Test
    void should_declare_date_properties_as_epoch_millis() {
        assertEpochMillis(spec.path("components").path("schemas").path("ClientCertificate").path("properties").path("createdAt"));
        assertEpochMillis(
            spec.path("components").path("schemas").path("ClientCertificate").path("properties").path("certificateExpiration")
        );
        assertEpochMillis(spec.path("components").path("schemas").path("CreateClientCertificate").path("properties").path("startsAt"));
    }

    private static void assertEpochMillis(JsonNode property) {
        assertThat(property.path("type").asText()).isEqualTo("integer");
        assertThat(property.path("format").asText()).isEqualTo("int64");
    }
}
